#!/usr/bin/env python3
"""Bakes the glyphs 3dsDL draws into romfs/hanfont.png and a C table.

The console's shared font only covers what its own menus use, so a translated
build shows boxes for the rest. This renders every character the catalog uses,
plus printable ASCII, into one alpha atlas, and writes the metrics the screen
code needs to lay text out from it.

    python3 tools/make_hanfont.py path/to/NotoSansCJKsc-Regular.otf

Noto Sans CJK SC is under the SIL Open Font License 1.1; the licence ships in
tools/fonts/. Run from the repository root; needs Pillow.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
EM = 26          # ideograph size in atlas pixels
LINE = 30        # the line feed the system font gives, which the sizes assume
CELL = EM + 2    # a glyph plus a margin, so filtering does not bleed
COLS = 36
ATLAS_W = 1024      # the console wants power-of-two textures
ATLAS_H = 1024


def wanted():
    text = (ROOT / "zh" / "zh.tsv").read_text("utf-8")
    chars = {c for c in text
             if 0x3000 <= ord(c) <= 0x9FFF or 0xFF00 <= ord(c) <= 0xFFEF}
    chars.update(chr(c) for c in range(0x20, 0x7F))
    return sorted(chars)


def main():
    font_path = sys.argv[1] if len(sys.argv) > 1 else "tools/fonts/NotoSansCJKsc-Regular.otf"
    font = ImageFont.truetype(font_path, EM)
    chars = wanted()
    rows = (len(chars) + COLS - 1) // COLS
    height = CELL * rows
    if height > 1024:
        sys.exit(f"{len(chars)} glyphs need {height}px, over the 1024 limit")
    if height > ATLAS_H:
        sys.exit(f"{len(chars)} glyphs need {height}px, over the {ATLAS_H} limit")
    mask = Image.new("L", (ATLAS_W, ATLAS_H), 0)
    draw = ImageDraw.Draw(mask)

    entries = []
    for index, char in enumerate(chars):
        col, row = index % COLS, index // COLS
        draw.text((col * CELL + 1, row * CELL + 1), char, font=font, fill=255)
        entries.append((ord(char), col, row, round(font.getlength(char))))

    (ROOT / "romfs").mkdir(exist_ok=True)
    # White with the glyph's coverage as alpha, so a tint colours it.
    atlas = Image.new("RGBA", (ATLAS_W, ATLAS_H), (255, 255, 255, 0))
    atlas.putalpha(mask)
    atlas.save(ROOT / "romfs" / "hanfont.png")

    out = []
    out.append('#include "hanfont.h"')
    out.append("")
    out.append("// Generated by tools/make_hanfont.py: do not edit.")
    out.append("// Noto Sans CJK SC, SIL Open Font License 1.1.")
    out.append("")
    out.append("namespace hanfont {")
    out.append("")
    out.append(f"const int Cell = {CELL};")
    out.append(f"const int Columns = {COLS};")
    out.append(f"const int AtlasWidth = {ATLAS_W};")
    out.append(f"const int AtlasHeight = {ATLAS_H};")
    out.append(f"const int Em = {EM};")
    out.append(f"const int LineFeed = {LINE};")
    out.append("")
    out.append("const Glyph Glyphs[] = {")
    for code, col, row, advance in entries:
        out.append("    {0x%04X, %d, %d, %d}," % (code, col, row, advance))
    out.append("};")
    out.append("")
    out.append("const int Count = sizeof(Glyphs) / sizeof(Glyphs[0]);")
    out.append("")
    out.append("const Glyph *find(uint32_t codePoint)")
    out.append("{")
    out.append("    int low = 0;")
    out.append("    int high = Count - 1;")
    out.append("    while (low <= high) {")
    out.append("        const int middle = (low + high) / 2;")
    out.append("        if (Glyphs[middle].codePoint == codePoint) {")
    out.append("            return &Glyphs[middle];")
    out.append("        }")
    out.append("        if (Glyphs[middle].codePoint < codePoint) {")
    out.append("            low = middle + 1;")
    out.append("        } else {")
    out.append("            high = middle - 1;")
    out.append("        }")
    out.append("    }")
    out.append("    return nullptr;")
    out.append("}")
    out.append("")
    out.append("} // namespace hanfont")
    (ROOT / "source" / "app" / "hanfont.cpp").write_text("\n".join(out) + "\n", "utf-8")

    header = """#pragma once

#include <cstdint>

// The glyphs 3dsDL draws itself, baked from Noto Sans CJK SC so Chinese shows
// on a console whose shared font has none.
namespace hanfont {

struct Glyph {
    uint32_t codePoint;
    int column;
    int row;
    int advance;
};

extern const int Cell;
extern const int Columns;
extern const int AtlasWidth;
extern const int AtlasHeight;
extern const int Em;
extern const int LineFeed;
extern const Glyph Glyphs[];
extern const int Count;

// The glyph for a code point, or nullptr when this font does not carry it.
const Glyph *find(uint32_t codePoint);

} // namespace hanfont
"""
    (ROOT / "source" / "app" / "hanfont.h").write_text(header, "utf-8")
    print(f"{len(chars)} glyphs, atlas {ATLAS_W}x{ATLAS_H}, rows {rows}")


if __name__ == "__main__":
    main()
